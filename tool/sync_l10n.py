#!/usr/bin/env python3
"""Copies the shared language registry into the app.

The registry (dukaapp: application/language/registry.json) is the one place
where every UI string is edited, for the web and this app. This script writes
the app's local language files from it — the app translates offline, nothing
is downloaded:

  assets/l10n/<code>.json         key -> text for each language in the registry
  assets/l10n/languages.json      {version, languages: {code: name}}
  lib/core/l10n/registry_strings.dart
                                  AppStrings read from those files (generated)

Run it after changing the registry or adding a getter/method to AppStrings:

  python3 tool/sync_l10n.py [path/to/registry.json]

Registry keys "app_<key>" are this app's text for <key> where the web uses the
same key differently (e.g. app_settings -> settings).
"""
import json
import os
import re
import sys

APP = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_REGISTRY = os.path.join(APP, '..', 'dukaapp', 'application', 'language', 'registry.json')


def main():
    registry_path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_REGISTRY
    with open(registry_path, encoding='utf-8') as f:
        registry = json.load(f)
    strings = registry['strings']
    languages = registry.get('languages') or {'en': 'English'}

    out_dir = os.path.join(APP, 'assets', 'l10n')
    os.makedirs(out_dir, exist_ok=True)
    for code in languages:
        texts = {}
        for key, values in strings.items():
            texts[key] = values.get(code) or values.get('en') or ''
        for key in list(texts):
            if key.startswith('app_'):
                texts[key[4:]] = texts[key]
        with open(os.path.join(out_dir, f'{code}.json'), 'w', encoding='utf-8') as f:
            json.dump(dict(sorted(texts.items())), f, ensure_ascii=False, indent=1)
    with open(os.path.join(out_dir, 'languages.json'), 'w', encoding='utf-8') as f:
        json.dump({'version': registry.get('version', ''), 'languages': languages}, f, ensure_ascii=False, indent=1)

    write_registry_strings()

    # Country list of the register form (same file the backend validates with).
    countries_src = os.path.join(os.path.dirname(os.path.dirname(registry_path)), 'data', 'countries.json')
    if os.path.exists(countries_src):
        with open(countries_src, encoding='utf-8') as f:
            countries = json.load(f)
        with open(os.path.join(out_dir, 'countries.json'), 'w', encoding='utf-8') as f:
            json.dump(countries, f, ensure_ascii=False)

    # Keys AppStrings uses that the registry doesn't have yet (they show English).
    src = read_app_strings()
    used = set(re.findall(r'^\s*String (?:get )?(\w+)', src[src.index('abstract class AppStrings'):], re.M))
    missing = sorted(k for k in used if k not in strings and ('app_' + k) not in strings and k != 'profileImagePath')
    print(f"Wrote {len(languages)} language file(s) to assets/l10n (registry {registry.get('version', '')}).")
    if missing:
        print(f"{len(missing)} AppStrings key(s) missing from the registry: {', '.join(missing)}")


def read_app_strings():
    with open(os.path.join(APP, 'lib', 'core', 'l10n', 'app_strings.dart'), encoding='utf-8') as f:
        return f.read()


def write_registry_strings():
    src = read_app_strings()
    body = src[src.index('abstract class AppStrings'):]
    lines = []
    for name in re.findall(r'^\s*String get (\w+);', body, re.M):
        lines.append(f"  @override String get {name} => _t('{name}', _fallback.{name});")
    for name, params in re.findall(r'^\s*String (\w+)\(([^)]*)\);', body, re.M):
        args = [p.strip().split()[-1] for p in params.split(',') if p.strip()]
        call = ', '.join(args)
        if name == 'profileImagePath':
            lines.append(f"  @override String {name}({params}) => _fallback.{name}({call});")
            continue
        mapping = ', '.join(f"'{a}': {a}" for a in args)
        lines.append(f"  @override String {name}({params}) => _f('{name}', {{{mapping}}}, _fallback.{name}({call}));")

    dart = f"""// GENERATED by tool/sync_l10n.py — do not edit by hand.
// AppStrings read from the local language files (assets/l10n/<code>.json), which
// come from the shared registry. A missing text falls back to [EnStrings].

import 'app_strings.dart';

class RegistryStrings extends AppStrings {{
  RegistryStrings(this._texts, this._fallback);

  final Map<String, String> _texts;
  final AppStrings _fallback;

  String _t(String key, String fallback) => _texts[key] ?? fallback;

  /// Template text with "{{name}}" placeholders filled in.
  String _f(String key, Map<String, Object?> args, String fallback) {{
    var text = _texts[key];
    if (text == null) return fallback;
    args.forEach((name, value) => text = text!.replaceAll('{{$name}}', '${{value ?? ''}}'));
    return text!;
  }}

{chr(10).join(lines)}
}}
"""
    with open(os.path.join(APP, 'lib', 'core', 'l10n', 'registry_strings.dart'), 'w', encoding='utf-8') as f:
        f.write(dart)


if __name__ == '__main__':
    main()
